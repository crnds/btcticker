#!/usr/bin/env python3
"""
Fetch 30 days of CDC Action Zone blocks from Kraken and write to data/cdc.js.
Run manually or via cron: 5 0 * * * cd /path/to/btcticker && python3 fetch_cdc.py

Uses Kraken (not Binance) -- Binance blocks GitHub Actions IP ranges (HTTP 451).
"""

import json
import os
import sys
import tempfile
import time
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

DISPLAY  = 30    # blocks to show
LIMIT    = 100   # candles to use for EMA warmup (Kraken returns up to 720)
OUT_FILE = Path(__file__).parent / "data" / "cdc.js"
# interval=1440 = 1 day in minutes; close price is index 4 in each row
URL      = "https://api.kraken.com/0/public/OHLC?pair=XBTUSD&interval=1440"

# The workflow commits data/cdc.js whenever the bytes change. `generated` is a
# wall-clock stamp, so writing unconditionally would commit daily even on a
# day where every block is identical to the last run. `generated` itself
# can't be dropped from the payload -- db.html anchors its 30 day labels to it
# (dropping it would let stale data get labelled "today") -- so the guard
# lives here instead, comparing the semantic payload (the blocks) before
# deciding to write. The heartbeat bounds the on-disk stamp's age so db.html's
# own 24h/48h CDC-freshness notices don't fire on a healthy pipeline.
SEMANTIC_FIELDS = ("blocks",)
HEARTBEAT_SEC   = 20 * 3600

MAX_ATTEMPTS = 3
BACKOFF_SEC  = 5


def calc_ema(closes, period):
    k   = 2 / (period + 1)
    out = [None] * len(closes)
    out[period - 1] = sum(closes[:period]) / period
    for i in range(period, len(closes)):
        out[i] = closes[i] * k + out[i - 1] * (1 - k)
    return out


def read_existing(path):
    """Payload from a previously generated file; None if absent or unparseable."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None
    start, end = text.find("{"), text.rfind("}")
    if start == -1 or end == -1:
        return None
    try:
        return json.loads(text[start:end + 1])
    except json.JSONDecodeError:
        return None


def should_write(old, new, now, heartbeat_sec=HEARTBEAT_SEC):
    """True when the payload carries new information, or the stamp needs refreshing."""
    if old is None:
        return True
    if any(old.get(f) != new.get(f) for f in SEMANTIC_FIELDS):
        return True
    try:
        stamp = datetime.strptime(old["generated"], "%Y-%m-%dT%H:%M:%SZ") \
                        .replace(tzinfo=timezone.utc)
    except (KeyError, TypeError, ValueError):
        return True  # unreadable stamp -- rewrite rather than freeze it
    return (now - stamp).total_seconds() >= heartbeat_sec


def fetch_json(req, attempts=MAX_ATTEMPTS):
    """GET + parse with exponential backoff. No key-based 4xx here worth
    distinguishing (Kraken's error signal is in the 200 response body, checked
    by the caller), so every failure is retried."""
    last = None
    for i in range(attempts):
        try:
            with urllib.request.urlopen(req, timeout=15) as resp:
                return json.loads(resp.read())
        except Exception as e:
            last = e
        if i < attempts - 1:
            time.sleep(BACKOFF_SEC * (2 ** i))
    sys.exit(f"ERROR: Kraken fetch failed after {attempts} attempts: {last}")


def main():
    print("Fetching daily candles from Kraken...")
    req = urllib.request.Request(URL, headers={"User-Agent": "btcticker-cdc/1.0"})
    raw = fetch_json(req)

    if raw.get("error"):
        sys.exit(f"ERROR: Kraken returned error: {raw['error']}")

    # Response: {"result": {"XXBTZUSD": [[time,o,h,l,close,vwap,vol,count],...], "last":...}}
    result   = raw.get("result") or {}
    pair_key = next((k for k in result if k != "last"), None)
    if pair_key is None:
        sys.exit("ERROR: no pair data in Kraken response")
    candles  = result[pair_key][-LIMIT:]   # take last LIMIT rows
    closes   = [float(c[4]) for c in candles]

    # 26-candle EMA warmup plus 30 display blocks; a shorter response would
    # silently produce wrapped/garbage blocks via negative indexing
    if len(closes) < DISPLAY + 26:
        sys.exit(f"ERROR: only {len(closes)} candles, need {DISPLAY + 26}")

    ema12 = calc_ema(closes, 12)
    ema26 = calc_ema(closes, 26)

    blocks = []
    for i in range(len(closes) - DISPLAY, len(closes)):
        blocks.append({
            "bull":  ema12[i] > ema26[i],
            "today": i == len(closes) - 1,
            "diff":  round(abs(ema12[i] - ema26[i]), 2),
        })

    now = datetime.now(timezone.utc)
    payload = {
        "generated": now.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "blocks":    blocks,
    }

    if "--force" not in sys.argv and not should_write(read_existing(OUT_FILE), payload, now):
        print(f"Unchanged ({len(blocks)} blocks, stamp still fresh) -- leaving {OUT_FILE} untouched")
        return

    js = (
        "// Auto-generated by fetch_cdc.py -- do not edit manually\n"
        f"window.LOCAL_CDC = {json.dumps(payload, separators=(',', ':'))};\n"
    )
    # atomic replace so an interrupted run can't leave a truncated cdc.js
    fd, tmp = tempfile.mkstemp(dir=OUT_FILE.parent, suffix=".tmp")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(js)
    os.replace(tmp, OUT_FILE)
    print(f"Written {len(blocks)} blocks to {OUT_FILE}")
    print(f"Last block -- bull: {blocks[-1]['bull']}, diff: {blocks[-1]['diff']}")


if __name__ == "__main__":
    main()
